#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Рендер PLAN-DEVOPS-16.md из plan.json (источник правды — build_plan.py)."""
import json, os

ROOT = os.path.dirname(os.path.abspath(__file__))
plan = json.load(open(os.path.join(ROOT, "plan.json"), encoding="utf-8"))

L = ["# DevOps-спринт: подготовка к стажировке (16 дней, 3–18 октября 2026)",
     "",
     "**%d минут в день** — %d автоматизация на Python + %d инфраструктура/DevOps + %d конспект и разбор."
     % (plan["minutes_total"], plan["minutes_split"]["python"], plan["minutes_split"]["infra"],
        plan["minutes_split"]["notes"]),
     "",
     "Цель: верхнеуровнево закрыть карту компетенций стажировки DevOps в облачном провайдере и собрать "
     "один сквозной артефакт — сервис, который проходит путь коммит → CI → образ → деплой в k3s → мониторинг.",
     "",
     "Правило зачёта то же: **день закрыт = коммит за сегодня**. Пропущенное не догоняется, план — очередь.",
     "",
     "## Контрольные точки",
     "",
     "- **День 4** — свой образ в реестре (0.1.0) и проходящие тесты",
     "- **День 7** — сервис живёт в k3s, есть PVC и CronJob, разобран один сбой",
     "- **День 10** — алерт доходит в Telegram, написан runbook",
     "- **День 14** — проведён учебный инцидент и написан постмортем",
     "- **День 16** — сквозная демонстрация + питч на 3 минуты + 20 вопросов стажировки",
     "",
     "## Программа",
     ""]

week = None
for d in plan["days"]:
    if d["week"] != week:
        week = d["week"]
        L += ["", "## Неделя %d" % week, ""]
    L += ["### День %d — %s" % (d["day"], d["infra"]["topic"]), ""]
    L += ["- 🐍 **Автоматизация (%d мин):** %s" % (plan["minutes_split"]["python"], d["python"]["topic"]),
          "  - источник: %s" % d["python"]["source"],
          "  - теория: %s" % d["python"]["theory"],
          "  - код: %s" % d["python"]["code"],
          "- 🛠 **DevOps (%d мин):** %s" % (plan["minutes_split"]["infra"], d["infra"]["topic"]),
          "  - источник: %s" % d["infra"]["source"],
          "  - задача: %s" % d["infra"]["task"],
          "- 🎤 вопрос дня: %s" % d["question"],
          "- ✅ готово, если: %s" % d["done_criteria"],
          "- ⚡ если есть силы: %s" % d["bonus"],
          ""]

L += ["## Что делать после 18 октября", "",
      "19 октября движок сам возвращает основной 84-дневный план (день 17: аннотации типов и mypy + "
      "реестр образов и сканирование уязвимостей). Серия и рекорд переносятся автоматически, "
      "записи спринта остаются в истории со статусом `sprint`.", "",
      "Незакрытые дни спринта не догоняются — тема остаётся доступной в этой папке: "
      "`python3 ~/devops-sprint/today.py brief` возвращает карточку любого дня спринта.", ""]

open(os.path.join(ROOT, "PLAN-DEVOPS-16.md"), "w", encoding="utf-8").write("\n".join(L))
print("PLAN-DEVOPS-16.md: %d строк" % len(L))
